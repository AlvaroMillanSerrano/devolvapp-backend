-- ---------------------------------------------------------------------
-- Catálogos y parámetros
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS container_type (
    code                 VARCHAR(20)  PRIMARY KEY,               -- PET, LATA, BRIK, VIDRIO, MEZCLADO
    name                 VARCHAR(60)  NOT NULL,
    icon                 VARCHAR(40),
    max_bag_capacity     SMALLINT     NOT NULL CHECK (max_bag_capacity > 0),
    co2_kg_per_container NUMERIC(6,3) NOT NULL CHECK (co2_kg_per_container >= 0)
);

CREATE TABLE IF NOT EXISTS incident_type (
    code VARCHAR(30) PRIMARY KEY,
    name VARCHAR(80) NOT NULL
);

CREATE TABLE IF NOT EXISTS app_parameter (
    param_key   VARCHAR(50)  PRIMARY KEY,
    param_value VARCHAR(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- Zonas y códigos postales
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS zone (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(80) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Catálogo cerrado de CP (Málaga). La dirección del ciudadano solo puede usar uno de estos.
CREATE TABLE IF NOT EXISTS zip_code (
    code          CHAR(5)      PRIMARY KEY CHECK (code ~ '^[0-9]{5}$'),
    neighbourhood VARCHAR(80)  NOT NULL,
    lat           NUMERIC(9,6) NOT NULL,
    lng           NUMERIC(9,6) NOT NULL,
    zone_id       BIGINT REFERENCES zone(id) ON DELETE SET NULL   -- NULL = sin servicio todavía
);

-- ---------------------------------------------------------------------
-- Usuarios y acceso
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS d_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name           VARCHAR(80)  NOT NULL,
    last_name            VARCHAR(120) NOT NULL,
    email                VARCHAR(160) NOT NULL UNIQUE,
    id_card              VARCHAR(9)   UNIQUE,                     -- DNI/NIE
    phone_number         VARCHAR(15)  UNIQUE,
    password_hash        VARCHAR(100) NOT NULL,                   -- BCrypt
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    status               VARCHAR(12)  NOT NULL DEFAULT 'ACTIVA' CHECK (status IN ('ACTIVA', 'SUSPENDIDA')),
    preferred_zone_id    BIGINT REFERENCES zone(id) ON DELETE SET NULL,  -- solo recolectores
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Un usuario puede tener varios roles
CREATE TABLE IF NOT EXISTS user_role (
    user_id BIGINT      NOT NULL REFERENCES d_user(id) ON DELETE CASCADE,
    role    VARCHAR(12) NOT NULL CHECK (role IN ('CIUDADANO', 'RECOLECTOR', 'ADMIN')),
    PRIMARY KEY (user_id, role)
);

-- Dirección actual del ciudadano (1:1)
CREATE TABLE IF NOT EXISTS address (
    user_id     BIGINT       PRIMARY KEY REFERENCES d_user(id) ON DELETE CASCADE,
    street_type VARCHAR(20)  NOT NULL,                            -- Calle, Avenida, Plaza…
    street_name VARCHAR(120) NOT NULL,
    street_number VARCHAR(10) NOT NULL,
    floor       VARCHAR(10),
    letter      VARCHAR(10),
    zip_code    CHAR(5)      NOT NULL REFERENCES zip_code(code),
    city        VARCHAR(80)  NOT NULL DEFAULT 'Málaga',
    lat         NUMERIC(9,6),
    lng         NUMERIC(9,6)
);

CREATE TABLE IF NOT EXISTS refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES d_user(id) ON DELETE CASCADE,
    token_hash VARCHAR(100) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ  NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES d_user(id) ON DELETE CASCADE,
    token_hash VARCHAR(100) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ  NOT NULL,
    used_at    TIMESTAMPTZ
);

-- ---------------------------------------------------------------------
-- Planificación: quién recoge cada día y franjas horarias
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS zone_day_collector (
    zone_id      BIGINT   NOT NULL REFERENCES zone(id) ON DELETE CASCADE,
    day_of_week  SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- 1 = lunes
    collector_id BIGINT   NOT NULL REFERENCES d_user(id) ON DELETE RESTRICT,
    PRIMARY KEY (zone_id, day_of_week),
    CONSTRAINT uq_collector_one_zone_per_day UNIQUE (collector_id, day_of_week)
);

CREATE TABLE IF NOT EXISTS time_slot (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id     BIGINT   NOT NULL REFERENCES zone(id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time  TIME     NOT NULL,
    end_time    TIME     NOT NULL,
    capacity    SMALLINT NOT NULL CHECK (capacity > 0),
    active      BOOLEAN  NOT NULL DEFAULT TRUE,                   -- borrado lógico
    CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS zone_change_request (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collector_id      BIGINT      NOT NULL REFERENCES d_user(id) ON DELETE CASCADE,
    current_zone_id   BIGINT      REFERENCES zone(id) ON DELETE SET NULL,
    requested_zone_id BIGINT      NOT NULL REFERENCES zone(id) ON DELETE CASCADE,
    reason            TEXT,
    status            VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE'
                      CHECK (status IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'CANCELADA')),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at       TIMESTAMPTZ,
    resolved_by       BIGINT      REFERENCES d_user(id) ON DELETE SET NULL,
    response          TEXT
);

-- ---------------------------------------------------------------------
-- Recogidas (1 pedido = 1 recogida) y bolsas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS collection (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(12) NOT NULL UNIQUE,                 -- P-1001
    citizen_id       BIGINT      NOT NULL REFERENCES d_user(id) ON DELETE RESTRICT,
    zone_id          BIGINT      NOT NULL REFERENCES zone(id) ON DELETE RESTRICT,
    collector_id     BIGINT      REFERENCES d_user(id) ON DELETE SET NULL,
    time_slot_id     BIGINT      REFERENCES time_slot(id) ON DELETE SET NULL,
    collection_date  DATE        NOT NULL,
    start_time       TIME        NOT NULL,                        -- copia de la franja
    end_time         TIME        NOT NULL,
    -- copia de la dirección en el momento de pedir
    addr_street_type   VARCHAR(20)  NOT NULL,
    addr_street_name   VARCHAR(120) NOT NULL,
    addr_street_number VARCHAR(10)  NOT NULL,
    addr_floor         VARCHAR(10),
    addr_letter        VARCHAR(10),
    addr_zip_code      CHAR(5)      NOT NULL,
    addr_city          VARCHAR(80)  NOT NULL,
    addr_lat           NUMERIC(9,6),
    addr_lng           NUMERIC(9,6),
    status           VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE'
                     CHECK (status IN ('PENDIENTE', 'EN_CAMINO', 'COMPLETADA', 'CANCELADA')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at       TIMESTAMPTZ,
    completed_at     TIMESTAMPTZ,
    cancelled_at     TIMESTAMPTZ,
    cancelled_by     BIGINT      REFERENCES d_user(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS bag (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id     BIGINT      NOT NULL REFERENCES collection(id) ON DELETE CASCADE,
    code              VARCHAR(8)  NOT NULL UNIQUE,                -- B-7F3K2
    quantity          SMALLINT    NOT NULL CHECK (quantity > 0),  -- total de contenidos de la bolsa
    max_capacity      SMALLINT    NOT NULL CHECK (max_capacity > 0),
    result            VARCHAR(14) CHECK (result IN ('ACEPTADA', 'DISCREPANCIA', 'NO_ENCONTRADA')),
    valid_containers  SMALLINT    CHECK (valid_containers >= 0),
    note              TEXT,
    CHECK (quantity <= max_capacity)
);

-- Una bolsa puede contener cantidades de varios tipos de envase.
CREATE TABLE IF NOT EXISTS bag_content (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bag_id             BIGINT      NOT NULL REFERENCES bag(id) ON DELETE CASCADE,
    container_type_code VARCHAR(20) NOT NULL REFERENCES container_type(code) ON DELETE RESTRICT,
    quantity           SMALLINT    NOT NULL CHECK (quantity > 0),
    UNIQUE (bag_id, container_type_code)
);

-- Mantiene bag.quantity sincronizada con la suma de sus contenidos.
CREATE OR REPLACE FUNCTION sync_bag_quantity_from_contents() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' OR TG_OP = 'UPDATE' THEN
        UPDATE bag
        SET quantity = COALESCE((SELECT SUM(quantity) FROM bag_content WHERE bag_id = OLD.bag_id), 0)
        WHERE id = OLD.bag_id;
    END IF;

    IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
        IF TG_OP <> 'UPDATE' OR NEW.bag_id <> OLD.bag_id THEN
            UPDATE bag
            SET quantity = COALESCE((SELECT SUM(quantity) FROM bag_content WHERE bag_id = NEW.bag_id), 0)
            WHERE id = NEW.bag_id;
        END IF;
    END IF;

    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_sync_bag_quantity
AFTER INSERT OR UPDATE OR DELETE ON bag_content
FOR EACH ROW EXECUTE FUNCTION sync_bag_quantity_from_contents();

-- Liquidación económica y de CO2 de cada recogida (idempotente: una por recogida)
CREATE TABLE IF NOT EXISTS settlement (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id    BIGINT        NOT NULL UNIQUE REFERENCES collection(id) ON DELETE RESTRICT,
    valid_containers INT           NOT NULL CHECK (valid_containers >= 0),
    total_amount     NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    citizen_share    NUMERIC(10,2) NOT NULL CHECK (citizen_share >= 0),
    company_share    NUMERIC(10,2) NOT NULL CHECK (company_share >= 0),
    co2_kg           NUMERIC(10,3) NOT NULL CHECK (co2_kg >= 0),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Incidencias
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS incident (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(12) NOT NULL UNIQUE,                    -- INC-2001
    collection_id BIGINT      NOT NULL REFERENCES collection(id) ON DELETE CASCADE,
    bag_id        BIGINT      REFERENCES bag(id) ON DELETE SET NULL,
    type          VARCHAR(30) NOT NULL REFERENCES incident_type(code),
    description   TEXT        NOT NULL,
    status        VARCHAR(12) NOT NULL DEFAULT 'ABIERTA' CHECK (status IN ('ABIERTA', 'EN_REVISION', 'RESUELTA')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by    BIGINT      NOT NULL REFERENCES d_user(id) ON DELETE RESTRICT,
    resolution    TEXT,
    resolved_at   TIMESTAMPTZ,
    CHECK (status <> 'RESUELTA' OR resolution IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS incident_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT       NOT NULL REFERENCES incident(id) ON DELETE CASCADE,
    occurred_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    author_id   BIGINT       REFERENCES d_user(id) ON DELETE SET NULL,
    action      VARCHAR(120) NOT NULL
);

-- ---------------------------------------------------------------------
-- Monedero: retiradas y remesas
-- Saldo = SUM(settlement.citizen_share) - SUM(withdrawal.amount WHERE status <> 'FALLIDA')
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS remittance (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(25)   NOT NULL UNIQUE,            -- REM-20261016-094633
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by          BIGINT        NOT NULL REFERENCES d_user(id) ON DELETE RESTRICT,
    transfer_count      INT           NOT NULL CHECK (transfer_count > 0),
    total               NUMERIC(10,2) NOT NULL CHECK (total > 0)
);

CREATE TABLE IF NOT EXISTS withdrawal (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(12)   NOT NULL UNIQUE,                -- R-501
    citizen_id      BIGINT        NOT NULL REFERENCES d_user(id) ON DELETE RESTRICT,
    amount          NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    iban            VARCHAR(34)   NOT NULL,
    status          VARCHAR(12)   NOT NULL DEFAULT 'PENDIENTE' CHECK (status IN ('PENDIENTE', 'COMPLETADA', 'FALLIDA')),
    requested_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    processed_at    TIMESTAMPTZ,
    processed_by    BIGINT        REFERENCES d_user(id) ON DELETE SET NULL,
    bank_reference  VARCHAR(30)   UNIQUE,                         -- TRF-AAAAMMDD-000id, la genera el servidor
    remittance_id   BIGINT        REFERENCES remittance(id) ON DELETE SET NULL,
    failure_reason  TEXT
);

CREATE TABLE IF NOT EXISTS withdrawal_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    withdrawal_id BIGINT      NOT NULL REFERENCES withdrawal(id) ON DELETE CASCADE,
    status        VARCHAR(12) NOT NULL,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    author_id     BIGINT      REFERENCES d_user(id) ON DELETE SET NULL
);

