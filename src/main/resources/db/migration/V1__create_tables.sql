CREATE TABLE IF NOT EXISTS d_user
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    u_name VARCHAR(100) NOT NULL,
    surname VARCHAR(100) NOT NULL,
    id_card VARCHAR(18) NOT NULL UNIQUE,
    phone_number VARCHAR(20) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    u_role VARCHAR(20) NOT NULL DEFAULT 'ciudadano' CHECK (u_role IN
        ('ciudadano', 'recolector', 'admin')),
    wallet DECIMAL(10, 2) NOT NULL DEFAULT 0.00 CHECK (wallet >= 0.00),
    city VARCHAR(100) NOT NULL,
    street VARCHAR(150) NOT NULL,
    building VARCHAR(20),
    floor VARCHAR(20),
    letter VARCHAR(10),
    zip_code VARCHAR(10) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    isActive BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS packet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    container JSONB NOT NULL,
    container_quantity INT NOT NULL CHECK (container_quantity > 0)
);

CREATE TABLE collection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    packet_id BIGINT NOT NULL,
    collection_start_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    collection_end_date TIMESTAMP NULL,
    state VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (state IN ('pendiente', 'en_camino', 'completada', 'cancelada')),
    CONSTRAINT fk_collection_user FOREIGN KEY (user_id) REFERENCES d_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_collection_packet FOREIGN KEY (packet_id) REFERENCES packet(id) ON DELETE RESTRICT
);

CREATE TABLE incident (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    description TEXT NOT NULL,
    date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_incident_collection FOREIGN KEY (collection_id) REFERENCES collection(id) ON DELETE CASCADE
);

CREATE TABLE collection_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_name VARCHAR(100) NOT NULL,
    zip_code VARCHAR(10) NOT NULL,
    collection_days VARCHAR(100) NOT NULL, -- Ej: 'Lunes, Miércoles, Viernes'
    collection_time VARCHAR(100) NOT NULL  -- Ej: '08:00 - 12:00'
);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_number VARCHAR(34) NOT NULL, -- Formato IBAN estándar
    quantity DECIMAL(10, 2) NOT NULL CHECK (quantity > 0.00),
    payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    state VARCHAR(20) NOT NULL DEFAULT 'solicitado' CHECK (state IN ('solicitado', 'procesado', 'rechazado')),
    CONSTRAINT fk_payment_user FOREIGN KEY (user_id) REFERENCES d_user(id) ON DELETE RESTRICT
);

CREATE INDEX idx_user_zip_code ON d_user(zip_code);
CREATE INDEX idx_collection_user ON collection(user_id);
CREATE INDEX idx_collection_state ON collection(state);
CREATE INDEX idx_schedule_cp ON collection_schedule(zip_code);
CREATE INDEX idx_payment_user ON payment(user_id);